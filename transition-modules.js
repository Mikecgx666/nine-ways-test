const expandToTwentySeven = (moduleId, extension) => {
  const module = window.TRANSITION_MODULES[moduleId];
  const sourceQuestions = module.questions;
  const sourceChapters = module.chapters;
  const toQuestion = (entry) => [entry[1], entry[2], entry[3]];
  const toChapter = (entry) => entry[0];
  const acts = [
    [sourceQuestions.slice(0, 4), sourceChapters.slice(0, 4), extension.entering],
    [sourceQuestions.slice(4, 8), sourceChapters.slice(4, 8), extension.collaborating],
    [sourceQuestions.slice(8, 12), sourceChapters.slice(8, 12), extension.owning]
  ];
  module.questions = acts.flatMap(([originals, labels, additions]) => [...originals, ...additions.map(toQuestion)]);
  module.chapters = acts.flatMap(([originals, labels, additions]) => [...labels, ...additions.map(toChapter)]);
};

